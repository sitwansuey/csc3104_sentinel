"""Generate draft release notes from git history and the committed registers.

The merged pull requests come from the first-parent history since the
previous version tag: GitHub merge commits ('Merge pull request #N from ...',
title on the first body line) and squash merges ('Title (#N)'). Commits that
reached that history without a pull request are counted, not hidden. Known
limitations come from docs/limitations.json and the evidence summary from
evidence/index.json, so the notes repeat no hand-typed results.

The output is a draft for a human to review before the release is published.
Nothing is written to git or GitHub.

  python scripts/release/notes.py --tag v1.0.0-rc.1 --output dist/RELEASE_NOTES.md
"""

import argparse
from collections import Counter
from dataclasses import dataclass
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.release.policy import IMAGES, ReleaseError, tag_version, version_key

MERGE = re.compile(r"Merge pull request #(\d+) from (\S+)")
SQUASH = re.compile(r"(.+?) \(#(\d+)\)")


def git_runner(root=ROOT):
    def run(args):
        result = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, encoding="utf-8",
                                check=False, timeout=60)
        if result.returncode:
            raise ReleaseError(f"git {' '.join(args[:2])} failed: {result.stderr.strip()[:300]}")
        return result.stdout
    return run


@dataclass(frozen=True)
class Pull:
    number: int
    title: str
    commit: str


def previous_tag(git, tag):
    """The highest version tag reachable from HEAD that sorts below `tag`."""
    current = version_key(tag_version(tag))
    earlier = []
    for name in git(["tag", "--list", "v*", "--merged", "HEAD"]).split():
        try:
            key = version_key(tag_version(name))
        except ReleaseError:
            continue
        if key < current:
            earlier.append((key, name))
    return max(earlier)[1] if earlier else None


def merged_pulls(git, since):
    """Pull requests merged on the first-parent history since `since`, and the other commit count."""
    span = f"{since}..HEAD" if since else "HEAD"
    log = git(["log", "--first-parent", "--format=%H%x1f%s%x1f%b%x1e", span])
    pulls, others = [], 0
    for record in log.split("\x1e"):
        record = record.strip("\r\n")
        if not record:
            continue
        commit, subject, body = (record.split("\x1f") + ["", ""])[:3]
        merge, squash = MERGE.fullmatch(subject.strip()), SQUASH.fullmatch(subject.strip())
        if merge:
            branch = merge.group(2).partition("/")[2] or merge.group(2)
            title = next((line.strip() for line in body.splitlines() if line.strip()), f"(no title; branch {branch})")
            pulls.append(Pull(int(merge.group(1)), title, commit))
        elif squash:
            pulls.append(Pull(int(squash.group(2)), squash.group(1).strip(), commit))
        else:
            others += 1
    return sorted(pulls, key=lambda pull: pull.number), others


def load_json(path):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ReleaseError(f"cannot read {path}: {error}") from None


def render(tag, revision, previous, pulls, others, limitations, index):
    version = tag_version(tag)
    lines = [f"# Sentinel {tag}", "",
             "Draft generated by `scripts/release/notes.py`. Review it before publishing.", "",
             f"- Source revision: `{revision}`",
             f"- Previous release: {previous or 'none (first tagged release)'}",
             "- Pre-release: " + ("yes (release candidate)" if "-rc." in version else "no"), "",
             "## Merged pull requests", ""]
    lines += [f"- #{pull.number} {pull.title}" for pull in pulls] or ["- None."]
    if others:
        lines += ["", f"{others} other commit(s) reached the first-parent history without a pull request."]
    lines += ["", "## Images", "",
              "Built on a GitHub-hosted runner from this tag for linux/amd64 and scanned with the project's "
              "pinned Trivy. The release fails on a High or Critical finding that has a fix, unless "
              "`.trivyignore` waives it with an issue link and an expiry date. Findings with no fix "
              "are listed in each image's full report but do not block the release. Third-party images "
              "(Online Boutique, kind nodes, the grpcurl probe) are not built or scanned here.", ""]
    lines += [f"- `{image.name}:{version}` from `{image.dockerfile}`" for image in IMAGES]
    lines += ["", "Each image ships as a `docker save` archive with a CycloneDX SBOM, a full Trivy report "
              "and a gate report. `release-manifest.json` records image IDs, labels, scanner version and "
              "finding counts; `SHA256SUMS` covers every asset.", "",
              "## Evidence", ""]
    current = [bundle for bundle in index.get("bundles", []) if bundle.get("status") == "current"]
    counts = Counter(bundle.get("provenance", "unknown") for bundle in current)
    lines.append(f"{len(current)} current evidence bundles: " + ", ".join(
        f"{counts[name]} {name}" for name in sorted(counts)) + ".")
    if counts.get("inferred"):
        lines.append("Inferred bundles predate provenance stamping; they are history, not proof of this tag.")
    lines += ["Results tables: `docs/results.md`. Quotable claims and their caveats: `evidence/claims.json`.",
              "", "## Known limitations", ""]
    entries = [entry for entry in limitations.get("entries", []) if entry.get("status") in {"open", "mitigated"}]
    lines += [f"- {entry['id']} ({entry['status']}): {entry['title']}" for entry in entries] or ["- None recorded."]
    lines += ["", "Details, workarounds and issue links: `docs/limitations.md`.", ""]
    return "\n".join(lines)


def generate(tag, git, root=ROOT, revision=None):
    previous = previous_tag(git, tag)
    pulls, others = merged_pulls(git, previous)
    revision = revision or git(["rev-parse", "HEAD"]).strip()
    return render(tag, revision, previous, pulls, others, load_json(Path(root, "docs/limitations.json")),
                  load_json(Path(root, "evidence/index.json")))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tag", required=True, help="Release tag, e.g. v1.0.0-rc.1")
    parser.add_argument("--revision", help="Source revision to state (default: HEAD)")
    parser.add_argument("--output", type=Path, help="Write the notes here instead of standard output")
    args = parser.parse_args(argv)
    try:
        text = generate(args.tag, git_runner(), revision=args.revision)
    except ReleaseError as error:
        print(f"notes: {error}", file=sys.stderr)
        return 1
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
