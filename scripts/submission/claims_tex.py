"""Render evidence/claims.json as LaTeX macros, so the article never retypes a number.

    python scripts/submission/claims_tex.py --verify --output article/generated/claims.tex
    python scripts/submission/claims_tex.py --check-source article/main.tex docs/submission/article-outline.md

For each claim, C-AGENT-WARM for example, four macros are defined:

  \\ClaimAgentWarm            the value                    3/3
  \\ClaimAgentWarmStatement   the sentence with the value  qwen3:14b agent mode reached ...
  \\ClaimAgentWarmCaveat      the mandatory scope caveat
  \\ClaimAgentWarmBundles     how many evidence bundles support it

Digits in an id are spelled out (LaTeX command names are letters only), and two
claims that would produce the same macro name are an error. Text is escaped for
LaTeX. --verify first runs the same check as 'summarize.py --check', so stale
claim values are refused. --check-source reports every \\Claim... macro a file
uses that is not generated, and every claim id (C-...) it names that is not in
evidence/claims.json. Standard library only, offline.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

CLAIMS = "evidence/claims.json"
CLAIM_ID = re.compile(r"^C-[A-Z0-9]+(?:-[A-Z0-9]+)*$")
CLAIM_MENTION = re.compile(r"(?<![A-Za-z0-9-])C-[A-Z0-9]+(?:-[A-Z0-9]+)*(?![A-Za-z0-9-])")
MACRO_USE = re.compile(r"\\(Claim[A-Za-z]+)")
SUFFIXES = ("", "Statement", "Caveat", "Bundles")
DIGITS = ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")
ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


class ClaimsError(ValueError):
    """claims.json is missing or malformed, or two claims map to one macro name."""


def macro_base(claim_id):
    """C-AGENT-WARM -> ClaimAgentWarm; C-T1 -> ClaimTOne."""
    if not CLAIM_ID.match(claim_id):
        raise ClaimsError(f"claim id {claim_id!r} is not of the form C-WORD-WORD")
    words = []
    for part in claim_id[2:].split("-"):
        word = "".join(DIGITS[int(char)] if char.isdigit() else char for char in part.capitalize())
        words.append(word[0].upper() + word[1:])
    return "Claim" + "".join(words)


def escape(text):
    return "".join(ESCAPES.get(char, char) for char in str(text))


def load(root=ROOT):
    path = Path(root, CLAIMS)
    if not path.is_file():
        raise ClaimsError(f"{CLAIMS} is missing")
    raw = path.read_bytes()
    try:
        data = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ClaimsError(f"{CLAIMS} is not valid JSON: {error}") from error
    claims = data.get("claims") if isinstance(data, dict) else None
    if not isinstance(claims, list):
        raise ClaimsError(f"{CLAIMS} has no 'claims' list")
    for claim in claims:
        missing = [key for key in ("id", "text", "value", "scope_caveat", "bundles")
                   if not isinstance(claim, dict) or key not in claim]
        if missing:
            raise ClaimsError(f"{CLAIMS}: claim {claim.get('id') if isinstance(claim, dict) else claim!r} "
                              f"lacks {', '.join(missing)}")
    return claims, hashlib.sha256(raw).hexdigest()


def macros(claims):
    """Ordered (name, LaTeX body) pairs for every claim; a repeated name is an error."""
    result, owners = [], {}
    for claim in claims:
        base = macro_base(claim["id"])
        statement = str(claim["text"]).replace("{value}", str(claim["value"]))
        bodies = (claim["value"], statement, claim["scope_caveat"], len(claim["bundles"]))
        for suffix, body in zip(SUFFIXES, bodies, strict=True):
            name = base + suffix
            if name in owners:
                raise ClaimsError(f"claims {owners[name]} and {claim['id']} both map to \\{name}")
            owners[name] = claim["id"]
            result.append((name, escape(body)))
    return result


def render(claims, digest):
    lines = ["% Generated by scripts/submission/claims_tex.py from evidence/claims.json. Do not edit.",
             f"% evidence/claims.json sha256: {digest}"]
    for claim in claims:
        lines.append(f"% {claim['id']}")
        lines.extend(f"\\newcommand{{\\{name}}}{{{body}}}" for name, body in macros([claim]))
    return "\n".join(lines) + "\n"


def source_problems(paths, claims):
    """Macros and claim ids used in the given files that the claims do not define."""
    defined = {name for name, _ in macros(claims)}
    known = {claim["id"] for claim in claims}
    problems = []
    for path in paths:
        text = Path(path).read_text(encoding="utf-8")
        for name in sorted(set(MACRO_USE.findall(text)) - defined):
            problems.append(f"{path}: uses \\{name}, which evidence/claims.json does not define")
        for claim_id in sorted(set(CLAIM_MENTION.findall(text)) - known):
            problems.append(f"{path}: names claim {claim_id}, which is not in evidence/claims.json")
    return problems


def verify(root):
    """The summarize.py --check result as (passed, its output)."""
    from scripts.evidence import summarize

    out = io.StringIO()
    try:
        code = summarize.run(Path(root), check=True, out=out)
    except summarize.EvidenceError as error:
        return False, str(error)
    return code == 0, out.getvalue()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    parser.add_argument("--output", type=Path, help="write the macros here instead of to standard output")
    parser.add_argument("--verify", action="store_true", help="refuse unless summarize.py --check passes")
    parser.add_argument("--check-source", nargs="+", type=Path, metavar="FILE",
                        help="report undefined \\Claim macros and unknown claim ids in these files")
    args = parser.parse_args(argv)
    try:
        claims, digest = load(args.root)
        if args.check_source:
            problems = source_problems(args.check_source, claims)
            for problem in problems:
                print("FAIL: " + problem)
            if not problems:
                print(f"Every claim macro and id in {len(args.check_source)} file(s) is defined")
            return 1 if problems else 0
        if args.verify:
            passed, output = verify(args.root)
            if not passed:
                print("FAIL: summarize.py --check does not pass; claim values may be stale\n" + output,
                      file=sys.stderr)
                return 1
        text = render(claims, digest)
    except ClaimsError as error:
        print("FAIL: " + str(error), file=sys.stderr)
        return 2
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {len(claims)} claims to {args.output}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
